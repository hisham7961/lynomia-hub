    public function handle(): int
    {
        $made = 0;
        foreach (self::RULES as [$name, $mod, $field, $op, $val, $msg, $every]) {
            if (DB::table('alert_rules')->where('name', $name)->exists()) continue;

            DB::table('alert_rules')->insert([
                'id' => (string) Str::uuid(), 'name' => $name,
                'mod' => $mod, 'field' => $field, 'op' => $op, 'val' => $val, 'msg' => $msg,
                'chan' => 'داخل النظام', 'every' => $every,
                'status' => 'متوقفة',           // كلها متوقفة — المستخدم يفعّل ما يريد
                'notes' => 'قاعدة انطلاقية جاهزة — فعّلها إن ناسبتك وعدّل قيمها بحرية',
                'created_at' => now(), 'updated_at' => now(),
            ]);
            $made++;
        }

        $this->info($made
            ? "أُنشئت {$made} قاعدة تنبيه متوقفة — فعّل ما يناسبك من شاشة قواعد التنبيه"
            : 'كل قواعد الانطلاق موجودة أصلاً');

        return self::SUCCESS;
    }
