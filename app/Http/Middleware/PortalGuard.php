<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

/**
 * **حارسُ البوابة** (Work OS · الطور A · WP-A.3 · SF-5) — سياجُ العزل الصلب
 * لحسابات العملاء، فوق مصفوفة الأدوار لا بديلاً عنها.
 *
 * قاعدةٌ واحدةٌ صريحة: حسابُ العميل (`account_type=client`) يبلغ **قائمةً بيضاءَ
 * محدودةً** فحسب — بوابتَه، ومشاريعَه، وفواتيرَه، وارتباطاته، وحسابَه، والخروج —
 * وكلُّ ما عداه **٤٠٤** (لا ٤٠٣: لا نُثبت وجودَ ما لا يخصّه، على نمط
 * `findScoped()->findOrFail`). والقرارُ هنا **فوق المصفوفة**: دورُ عميلٍ مُساءُ
 * الضبط يُمنح `servers:v` — أو المصفوفةَ كاملةً — لا يُسرّب حرفاً، فالحارسُ يردّه
 * قبل أن تُستشار المصفوفةُ أصلاً.
 *
 * **لماذا قائمةٌ بيضاءُ لا سوداء (درسُ النقد C1):** من ٨٢ وحدة، ١٥ فقط لها عمودُ
 * عميلٍ يعزلها `hub_scope`؛ الـ٦٧ الباقية (servers/vault/dbs/domains/payroll/
 * banks/costc/phones/accounts/hr…) بلا أيّ ترشيحِ عميلٍ من الرصيف — فلو مُنِح
 * دورُ العميلِ إحداها لعادت **كلَّ** صفوفها بلا فلتر. قائمةٌ سوداءُ من بضع وحداتٍ
 * تترك عشراتٍ مفتوحة؛ الافتراضُ **منعٌ**، والاستثناءُ يُعدَّد.
 *
 * والمستخدمُ الداخليّ (`account_type=internal` — الافتراض) لا يمسّه الحارسُ
 * بتاتاً: يمرّ كما كان، فلا انحدارَ على أيّ شاشةٍ داخلية.
 *
 * لا محرّكَ عزلٍ ثانٍ: التصنيفُ من `hub_is_client` (يقرأ العمودَ الصلب)، والعزلُ
 * الأدقُّ للوحداتِ المسموحة (أيُّ صفوفٍ يرى) يبقى في `hub_scope` بعد الحارس.
 */
class PortalGuard
{
    /**
     * أسماءُ المسارات (أنماطُ `routeIs`) التي يبلغها حسابُ العميل — عدا مساراتِ
     * الوحدات `m.*` التي تُحكَم بقائمة الوحدات أدناه. القائمةُ متحفِّظةٌ عمداً:
     *  • `logout`        — الخروجُ دائماً متاح.
     *  • `portal.*`      — بوابةُ العميل والخدمةُ الذاتية (يبني عليها الطورُ B تحت
     *                      البادئة نفسِها؛ `portal.employee` يظلّ محروساً بـ`hr:v`
     *                      في متحكّمه فلا يتسرّب ملفُّ موظفٍ ولو بلغه الطلب).
     *  • `profile.*`     — إدارةُ الحساب الذاتيّ (كلمةُ السرّ/التنبيهات/2FA) — كلُّها
     *                      على النفس، فلا مساسَ بغيره.
     */
    protected const NAME_ALLOW = [
        'logout',
        'portal.*',
        'profile.*',
    ];

    /**
     * وحداتُ `m.*` التي يبلغها العميل — الرؤيةُ الأدقُّ (audience/hub_scope) تجري
     * بعد الحارس في المتحكّم؛ الحارسُ يمنع الـ٦٧ الداخلية بالكامل. باقي الـ١٥
     * المنطَّقةِ بعميلٍ — quotes بهامشها، purchases بتكلفتها، assets/contracts… —
     * محجوبةٌ هنا عمداً: العزلُ يُشدُّ لا يُرخى. (الوثائقُ والقنواتُ تُضاف حين تهبط
     * وحداتُها/مساراتُها في الطورين B/C/D.)
     */
    protected const MODULE_ALLOW = [
        'engagements',   // ارتباطاتُ العميل
        'projects',      // مشاريعُه (audience=client يُطبَّق في المتحكّم)
        'fin',           // فواتيرُه (fin_documents) — منطَّقةٌ بعميله في hub_scope
    ];

    public function handle(Request $request, Closure $next): Response
    {
        // الحارسُ لا يعمل إلا على حساب عميلٍ مُصادَق؛ الداخليُّ والضيفُ يمرّان دون مساس
        if (! hub_is_client($request->user())) {
            return $next($request);
        }

        if ($this->clientMayReach($request)) {
            return $next($request);
        }

        // ٤٠٤ لا ٤٠٣: لا نكشف وجودَ ما لا يخصّه
        abort(404);
    }

    /** هل يبلغ حسابُ العميل هذا الطلب؟ — قائمةٌ بيضاءُ صريحة، والافتراضُ منع. */
    protected function clientMayReach(Request $request): bool
    {
        $route = $request->route();
        if ($route === null) {
            return false;
        }

        // ١) مساراتُ الوحدات `m.*`: القرارُ على مُعرِّف الوحدة لا على الاسم وحده —
        //    `/m/servers` و`/m/projects` يتقاسمان الاسمَ `m.index`، فالتمييزُ بالمُعامل.
        if ($request->routeIs('m.*')) {
            $module = (string) ($route->parameter('module') ?? '');

            return in_array($module, self::MODULE_ALLOW, true);
        }

        // ٢) بقيةُ المسارات: بالاسم (تطابقٌ تامٌّ أو بادئةٌ عبر أنماط routeIs)
        return $request->routeIs(...self::NAME_ALLOW);
    }
}
