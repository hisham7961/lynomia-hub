<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

/**
 * **حارسُ البوابة** (Work OS · الطور A · WP-A.3 · SF-5) — سياجُ العزل الصلب
 * لحسابات العملاء، فوق مصفوفة الأدوار لا بديلاً عنها.
 *
 * قاعدةٌ واحدةٌ صريحة: حسابُ العميل (`account_type=client`) يبلغ **قائمةً بيضاءَ
 * محدودةً** فحسب — بوابتَه، وحسابَه، والخروج — وكلُّ ما عداه ممنوع. والقرارُ هنا
 * **فوق المصفوفة**: دورُ عميلٍ مُساءُ الضبط يُمنح `servers:v` — أو المصفوفةَ
 * كاملةً — لا يُسرّب حرفاً، فالحارسُ يردّه قبل أن تُستشار المصفوفةُ أصلاً.
 *
 * **صورةُ المنع بحسبِ الطلب** (الجولة 1 · F22): طلبُ **تصفّحٍ** (GET/HEAD لا يطلب
 * JSON) يُحوَّل ٣٠٢ إلى بوّابةِ العميل — فصاحبُ الحساب الذي ضلَّ إلى `/m/fin` أو
 * `/dashboard` أو «بوابتي» يجد بوّابتَه لا ٤٠٤ محيّرةً ولا قشرةَ الويبِ الداخلية.
 * وكلُّ ما سواه (JSON/AJAX وكلُّ طريقةٍ غيرِ آمنة) يبقى **٤٠٤** (لا ٤٠٣: لا نُثبت
 * وجودَ ما لا يخصّه لعميلٍ يجسّ برمجيّاً، على نمط `findScoped()->findOrFail`).
 *
 * **لماذا قائمةٌ بيضاءُ لا سوداء (درسُ النقد C1):** من ٨٢ وحدة، ١٥ فقط لها عمودُ
 * عميلٍ يعزلها `hub_scope`؛ الـ٦٧ الباقية (servers/vault/dbs/domains/payroll/
 * banks/costc/phones/accounts/hr…) بلا أيّ ترشيحِ عميلٍ من الرصيف — فلو مُنِح
 * دورُ العميلِ إحداها لعادت **كلَّ** صفوفها بلا فلتر. قائمةٌ سوداءُ من بضع وحداتٍ
 * تترك عشراتٍ مفتوحة؛ الافتراضُ **منعٌ**، والاستثناءُ يُعدَّد.
 *
 * والمستخدمُ الداخليّ (`account_type=internal` — الافتراض) لا يمسّه الحارسُ
 * بتاتاً: يمرّ كما كان، فلا انحدارَ على أيّ شاشةٍ داخلية.
 *
 * لا محرّكَ عزلٍ ثانٍ: التصنيفُ من `hub_is_client` (يقرأ العمودَ الصلب)، والعزلُ
 * الأدقُّ للوحداتِ المسموحة (أيُّ صفوفٍ يرى) يبقى في `hub_scope` بعد الحارس.
 */
class PortalGuard
{
    /**
     * أسماءُ المسارات (أنماطُ `routeIs`) التي يبلغها حسابُ العميل. القائمةُ
     * متحفِّظةٌ عمداً:
     *  • `logout`        — الخروجُ دائماً متاح.
     *  • `portal.*`      — بوابةُ العميل والخدمةُ الذاتية (يبني عليها الطورُ B تحت
     *                      البادئة نفسِها) — **عدا** الأسماءِ الموظفيّةِ المستثناةِ
     *                      صراحةً في `clientMayReach` (بوابتي/عهدتي/ملف الموظف 360).
     *  • `profile.*`     — إدارةُ الحساب الذاتيّ (كلمةُ السرّ/التنبيهات/2FA) — كلُّها
     *                      على النفس، فلا مساسَ بغيره — **عدا** مفاتيحِ API (F23).
     */
    protected const NAME_ALLOW = [
        'logout',
        'portal.*',
        'profile.*',
    ];

    /**
     * قائمةُ الوحدات التي يقرؤها حسابُ العميل **عبر `/api/v1` حصراً** — مصدرُ
     * الحقيقةِ الواحد الذي يعيد استعمالَه متحكّمُ API (§14) وحارسُ الجوال.
     *
     * (الجولة 1 · F22) **قشرةُ الويب الداخلية `m.*` لم تعد تُفتَح لعميلٍ بتاتاً**:
     * كانت القائمةُ تسمح له بفتح `/m/fin`/`/m/projects` بشريطها الداخليّ كاملاً —
     * قرارُ «قراءةِ الوحدات السياقيّة» كان قرارَ **API** لا قرارَ قشرةٍ، والعميلُ
     * البشريُّ مكانُه شاشاتُ بوّابته (`portal.*`). فطلبُ تصفّحٍ على `m.*` يُحوَّل
     * لبوّابته، وما سواه ٤٠٤ (في `handle`).
     */
    public const MODULE_ALLOW = [
        'engagements',   // ارتباطاتُ العميل
        'projects',      // مشاريعُه (audience=client يُطبَّق في المتحكّم)
        'fin',           // فواتيرُه (fin_documents) — منطَّقةٌ بعميله في hub_scope
    ];

    public function handle(Request $request, Closure $next): Response
    {
        // الحارسُ لا يعمل إلا على حساب عميلٍ مُصادَق؛ الداخليُّ والضيفُ يمرّان دون مساس
        if (! hub_is_client($request->user())) {
            return $next($request);
        }

        if ($this->clientMayReach($request)) {
            return $next($request);
        }

        // (الجولة 1 · F22) **قشرةُ التصفّح الداخليّةُ يُحوَّل منها العميلُ لبوّابته**:
        // طلبُ تصفّحٍ (GET/HEAD لا يطلب JSON) على سطحٍ داخليٍّ يبلغه إنسانٌ ملاحةً —
        // وحداتُ `m.*`، ولوحةُ التحكّم، و«بوابتي» الموظفيّةُ وأخواتُها — يُردّ ٣٠٢
        // إلى بوّابته لا ٤٠٤ محيّرةً تُتيهه ولا قشرةً داخليّةً تُعرَض له.
        //
        // وما سواه يبقى **٤٠٤** (لا ٤٠٣ ولا تحويل): طلبُ JSON/AJAX، وكلُّ طريقةٍ
        // غيرِ آمنة، ومساراتٌ داخليّةٌ عميقةٌ/إداريّةٌ لا يبلغها إنسانٌ ملاحةً
        // (admin/collab/dm…) — حفاظاً على «لا كشفَ وجودٍ» (نمط findOrFail) الذي
        // يُقيَّد بالتحويل على سطوحِ الملاحةِ البشريّةِ وحدَها لا كلِّ مسار.
        if ($request->isMethodSafe() && ! $request->expectsJson() && $this->isHumanShell($request)) {
            return redirect()->route('portal.home');
        }

        // ٤٠٤ لا ٤٠٣: لا نكشف وجودَ ما لا يخصّه
        abort(404);
    }

    /** هل يبلغ حسابُ العميل هذا الطلب؟ — قائمةٌ بيضاءُ صريحة، والافتراضُ منع. */
    protected function clientMayReach(Request $request): bool
    {
        $route = $request->route();
        if ($route === null) {
            return false;
        }

        // ١) قشرةُ الوحدات `m.*` داخليّةٌ بالكامل (F22) — قراءةُ العميل البرمجيّة
        //    عبر `/api/v1` (MODULE_ALLOW هناك)، والبشريّةُ عبر شاشات بوّابته.
        if ($request->routeIs('m.*')) {
            return false;
        }

        // ٢) (الجولة 1 · F23) مفاتيحُ API لا يسكّها حسابُ عميل — تُستثنى من سماحِ
        //    `profile.*` صراحةً (سكٌّ وتدويرٌ وإبطال)، والمتحكّمُ يعيد الصدَّ دفاعاً في العمق.
        if ($request->routeIs('profile.token.*')) {
            return false;
        }

        // ٣) «بوابتي» الموظفيّةُ وأخواتُها داخليّةٌ رغم بادئةِ اسمِها `portal.` —
        //    شاشةُ الموظفِ الذاتيّة (مهامّ/إجازات/عهدة) والملفُّ 360 ليسا لعميل (F22).
        if ($request->routeIs('portal.me', 'portal.custody', 'portal.employee')) {
            return false;
        }

        // ٤) بقيةُ المسارات: بالاسم (تطابقٌ تامٌّ أو بادئةٌ عبر أنماط routeIs)
        return $request->routeIs(...self::NAME_ALLOW);
    }

    /**
     * **سطحُ تصفّحٍ داخليٌّ يبلغه إنسانٌ ملاحةً** (الجولة 1 · F22) — الوجهاتُ التي
     * يُحوَّل منها حسابُ العميلِ لبوّابته بدل ٤٠٤: قشرةُ الوحدات `m.*`، ولوحةُ
     * التحكّم، و«بوابتي» الموظفيّةُ وعهدتي. هي أمثلةُ المهمّة نفسُها (`/m/*`،
     * `/dashboard`، بوابتي) — دَعواتُ ملاحةٍ يقع فيها الحسابُ سهواً.
     *
     * **ملفُّ الموظف 360 (`portal.employee`) ليس منها**: كشفُ ملفِّ موظفٍ بعينه
     * سطحٌ حسّاسٌ يُصان بـ٤٠٤ «لا كشفَ وجود» (§79) — التحويلُ يُثبت أنّ المعرّفَ
     * حقيقيٌّ (302 مقابل 404)، فيبقى محجوباً صمتاً كما كان.
     */
    protected function isHumanShell(Request $request): bool
    {
        return $request->routeIs('m.*', 'dashboard', 'portal.me', 'portal.custody');
    }
}
