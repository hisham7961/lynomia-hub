<?php

namespace App\Support;

/**
 * **بابُ «اسأل Hub» وحدودُه** (المرحلة ٣ · P3-W2).
 *
 * ── **الثابتُ الحاكمُ فوقَ كلِّ شيءٍ في هذه المرحلة** ──
 *
 * > **`AI permissions ≤ current user permissions`**
 *
 * ولا يُنفَّذ هذا بوعدٍ في موجّهٍ نصّيّ بل **بالبناء**: لا يملك هذا الصنفُ ولا
 * ما بعده أيَّ هويّةِ خدمةٍ ولا مفتاحَ تجاوز. كلُّ قراءةٍ تُنفَّذ **بجلسةِ
 * المستخدمِ نفسِها** عبر `hub_scope`/`hub_can` — فما يُصَدُّ عنه في الشاشةِ
 * يُصَدُّ عنه هنا، **بالآليّةِ نفسِها لا بنسخةٍ منها**.
 *
 * ── **ورايةُ `aiAssistant` لا تمنح بيانات** ──
 *
 * تفتح **بابَ السؤالِ** لا بابَ البيانات. حاملُها يسأل، ويُجاب من نطاقِه هو.
 * ومن لا يملك وحدةً لا يراها بالسؤالِ كما لا يراها بالنقر. **والفرقُ بين
 * البابين هو ما يجعل الرايةَ آمنةَ المنح.**
 *
 * ── **وبوّابتان لا واحدة** ──
 *
 *  · **الصلاحيّة** `hub_flag(aiAssistant)` — أمصرَّحٌ لهذا المستخدم؟
 *  · **القدرة** `hub_capability('ai.assistant')` — أمتاحةٌ تشغيليّاً أصلاً؟
 *
 * وكلاهما يجب أن يمرّ. والثانيةُ تُطفئ الميزةَ للجميعِ بمفتاحٍ واحدٍ إن لزم،
 * **بلا مسِّ دورٍ واحد**.
 */
final class AskPolicy
{
    /** الرايةُ الموعودةُ منذ المرحلة ١ — وتُمنَح اليومَ لأنّها صارت تفتح شيئاً */
    public const FLAG = 'aiAssistant';

    /** مفتاحُ القدرةِ في سجلِّ القدرات */
    public const CAPABILITY = 'ai.assistant';

    /**
     * **الغرضُ الافتراضيُّ — والافتراضيُّ وحدَه.**
     *
     * الغرضُ الفعليُّ يُقرأ من `ask.profile` حيّاً (`profileKey()`)، وهذا ما
     * يجعل تبديلَ النموذجِ أو المزوّدِ **تغييرَ إعدادٍ من مركزِ الذكاء لا
     * تعديلَ شيفرة**. والثابتُ يبقى قيمةً ابتدائيّةً ومرجعاً للاختبارات.
     */
    public const PROFILE = 'general';

    /**
     * **سقوفٌ صلبةٌ لا اقتراحات.**
     *
     * وسقفُ السياقِ أهمُّها: نافذةُ النموذجِ ليست حارسَ تكلفةٍ ولا حارسَ تسريب.
     * سياقٌ متضخّمٌ يُنفق أكثرَ **ويُغرِق** الإجابةَ في صفوفٍ لا علاقةَ لها
     * بالسؤال، فتصير الدقّةُ أسوأَ كلّما كثُرت البيانات.
     */
    public const MAX_QUESTION_CHARS = 2000;
    public const MAX_CONTEXT_CHARS  = 24000;
    public const MAX_TOOL_CALLS     = 6;
    public const MAX_ROWS_PER_TOOL  = 25;

    /** سقفُ رموزِ المخرَجِ الافتراضيُّ للخطوةِ الواحدة */
    public const MAX_OUTPUT_TOKENS = 700;

    /**
     * ── **السقوفُ الصلبةُ — ما لا يرفعه إعداد** ──
     *
     * كلُّ سقفٍ أدناه له مفتاحُ إعدادٍ يُخفضه، **ولا مفتاحَ يرفعه فوق هذا**.
     * ولمَ سقفانِ لا واحد؟ لأنّ مفتاحَ الإعدادِ يُضبَط من شاشةٍ، ومن يملك
     * الشاشةَ يملك أن يكتب `999999` سهواً — **فيصير حارسُ الكلفةِ بابَ
     * إنفاقٍ بدل أن يكون سدَّه**. فالإعدادُ يضبط داخلَ المدى، والمدى في
     * الشيفرةِ حيث لا يبلغه خطأُ إدخال.
     */
    public const HARD_OUTPUT_TOKENS = 2000;
    public const HARD_MODEL_STEPS   = 10;
    public const HARD_TOOL_CALLS    = 10;

    /*
     * ── **وأرضيّاتٌ صلبةٌ أيضاً — ما لا يخفضه إعداد** (قبولُ الإنتاج · `OUTPUT_LIMIT`) ──
     *
     * **وسقفٌ بلا أرضيّةٍ ليس حارساً بل بابُ تعطيل.** كان المدى `[1, hard]`،
     * فقيمةٌ تُكتَب سهواً في الشاشةِ — `16` أو `0` أو سالب — تُقبَل صامتة،
     * فيُرسَل `max_tokens` ضئيلاً **ويموت كلُّ سؤالٍ بـ`OUTPUT_LIMIT`
     * والتهيئةُ تبدو سليمة**.
     *
     * والأرقامُ مشتقّةٌ لا مُختارة:
     *
     *  · **`MIN_OUTPUT_TOKENS = 256`** — أصغرُ سقفٍ تكتمل عنده دورةُ سؤالٍ
     *    واحدة: طلبُ أداةٍ بوسائطِه (`{"module":"projects"}` ≈ ٤٠ رمزاً) ثمّ
     *    جوابٌ عربيٌّ قصيرٌ باستشهادِه (≈ ٦٠). والباقي هامشٌ لنموذجٍ يكتب
     *    مقدّمةً قبل جوابِه. **وهو أكبرُ من سقفِ الفاحصِ D بستّةَ عشرَ ضعفاً**،
     *    فلا يرث المنتجُ ميزانيّةَ فحصٍ غرضُها إثباتُ توليدٍ أدنى بأرخصِ ثمن.
     *  · **`MIN_MODEL_STEPS = 2`** — خطوةُ أداةٍ وخطوةُ جواب. وبخطوةٍ واحدةٍ
     *    يطلب النموذجُ القراءةَ **ولا يبقى له نداءٌ يقول فيه ما قرأ**.
     *  · **`MIN_TOOL_CALLS = 1`** — قراءةٌ واحدةٌ على الأقلّ، وإلّا فلا مساعد.
     *
     * **ولا تُرفَع الأرضيّةُ فوق الافتراضيّ**: هي حدُّ ما يعمل، لا ما نُفضّل.
     */
    public const MIN_OUTPUT_TOKENS = 256;
    public const MIN_MODEL_STEPS   = 2;
    public const MIN_TOOL_CALLS    = 1;

    /**
     * **أقصى عددِ نداءاتِ توليدٍ في الطلبِ الواحد — بالإعاداتِ والاحتياطِ معاً.**
     *
     * وهذا هو **الحاجزُ الصلبُ للكلفة**، لا سقفُ الخطوات. لأنّ الخطوةَ الواحدةَ
     * قد تُعيد المحاولةَ مرّتين ثمّ تحتاط مرّتين — أي **خمسةَ نداءاتٍ لخطوةٍ
     * واحدة**. فسقفُ ستِّ خطواتٍ بلا هذا الحاجزِ يعني ثلاثين نداءً ممكناً
     * للسؤالِ الواحد. وسقفُ الكلفةِ التقديريُّ (`ask.cost_ceiling`) حارسٌ
     * ثانٍ اختياريٌّ فوقَه، **لا بديلٌ عنه**: التقديرُ يحتاج خريطةَ أسعار،
     * وهذا العددُ لا يحتاج شيئاً.
     */
    public const MAX_GENERATION_CALLS = 12;

    /** حدُّ المعدّل — كما `ai.test` وأخواتِها */
    public const THROTTLE = '20,1';

    // ── البوّابة ────────────────────────────────────────────────────────

    /**
     * **التخويلُ وحدَه — ولا شيءَ تشغيليٌّ فيه.**
     *
     * ── عيبٌ أمسكه اختبارُ العزلِ أثناءَ البناء ──
     *
     * كانت هذه الدالةُ تستشير `hub_capability('ai.assistant')` أوّلاً، وتلك
     * القدرةُ **مشتقّةٌ من جاهزيّةِ البوّابةِ والغرض**. فكان انقطاعُ البوّابةِ
     * **يقلب جوابَ سؤالٍ عن الصلاحيّة**: «أيملك فلانٌ حقَّ السؤال؟» تصير «لا»
     * لأنّ خدمةً خارجيّةً لا تردّ.
     *
     * وهذا خلطُ طبقتين: **التخويلُ حقيقةٌ عن المستخدم، والجاهزيّةُ حقيقةٌ عن
     * النظام**. وخلطُهما يجعل طبقةَ الأدواتِ — وهي قراءةُ بياناتِ Hub ولا
     * علاقةَ لها ببوّابةِ نماذجَ أصلاً — تتعطّل بعطلٍ لا يخصّها، **ويجعل أثرَ
     * التدقيقِ يقول «رُفض» حيث الصوابُ «تعذّر»**.
     *
     * فصارت: `canAsk` تخويلٌ محض، و`ready`/`whyNot` جاهزيّةٌ تشغيليّة.
     */
    public static function canAsk(mixed $user = null): bool
    {
        $u = $user ?? auth()->user();
        if ($u === null) return false;

        return hub_is_owner($u) || hub_flag($u, self::FLAG);
    }

    public static function gate(): void
    {
        abort_unless(self::canAsk(), 403,
            '«اسأل Hub» يحتاج صلاحيّةَ استعمالِ المساعد');
    }

    /**
     * **لماذا لا يُتاح؟** — بجملةٍ تُقال للمستخدمِ لا برمزٍ يُفكّ.
     *
     * و«غيرُ متاح» و«غيرُ مصرَّحٍ لك» و«لا غرضَ جاهز» ثلاثُ حالاتٍ مختلفة،
     * **وإصلاحُ كلٍّ منها مختلفٌ تماماً**. فخلطُها يجعل المديرَ يمنح رايةً
     * لمشكلةِ تهيئة.
     */
    public static function whyNot(mixed $user = null): ?string
    {
        $u = $user ?? auth()->user();

        /*
         * **والترتيبُ مقصود: الأخصُّ أوّلاً.**
         *
         * القدرةُ `ai.assistant` مشتقّةٌ من جاهزيّةِ البوّابةِ والغرض، فلو
         * قُدِّمت لابتلعت السببَ الحقيقيَّ وقالت «مُطفأةٌ من سجلِّ القدرات»
         * عن بوّابةٍ لم تُفحَص — **فيُرسَل المديرُ إلى الشاشةِ الخطأ**.
         */
        if (! hub_is_owner($u) && ! hub_flag($u, self::FLAG)) {
            return 'لا تملك صلاحيّةَ استعمالِ المساعد';
        }
        if (! AiGateway::enabled() || ! AiGateway::probePassed()) {
            return (string) (AiGateway::whyNotReady() ?? 'بوّابةُ النماذجِ غيرُ جاهزة');
        }
        if (self::profile() === null) {
            return 'لا غرضَ «' . self::profileKey() . '» بسلسلةٍ جاهزة — اربط نموذجاً بغرضٍ من قسمِ التوجيه';
        }
        if (! hub_capability(self::CAPABILITY)) {
            return 'مساعدُ Hub مُطفأٌ من سجلِّ القدرات';
        }

        return null;
    }

    /** أجاهزٌ للإجابةِ فعلاً؟ — البابُ والبوّابةُ والسلسلةُ معاً */
    public static function ready(mixed $user = null): bool
    {
        return self::whyNot($user) === null;
    }

    /**
     * **غرضُ التوجيهِ — بسلسلةٍ صالحةٍ لا بوجودِه** (درسُ W8).
     *
     * غرضٌ موجودٌ بسلسلةٍ فارغةٍ لا يُجيب طلباً، وعدُّه جاهزاً يجعل الشاشةَ
     * تطمئنّ حيث يجب أن تُنذر.
     */
    public static function profile(): ?\App\Models\AiProfile
    {
        $p = \App\Models\AiProfile::query()
            ->where('key', self::profileKey())->where('enabled', true)->first();

        if ($p === null) return null;

        return AiProfiles::chain($p)->isEmpty() ? null : $p;
    }

    // ── ما يُضبَط من الإعداداتِ لا من الشيفرة ──────────────────────────

    /**
     * **مفتاحُ غرضِ التوجيهِ كما ضبطه المالك** — أو الافتراضيّ.
     *
     * وقيمةٌ فارغةٌ لا تعني «بلا غرض» بل **«لم يُضبَط»**، فتعود إلى
     * الافتراضيّ بدل أن تُطفئ الميزةَ بصمت.
     */
    public static function profileKey(): string
    {
        $k = trim((string) setting('ask.profile', 'general'));

        return $k === '' ? self::PROFILE : $k;
    }

    /** سقفُ رموزِ المخرَجِ الفعليُّ — بين ١ والسقفِ الصلب */
    public static function maxOutputTokens(): int
    {
        return self::clamp(setting('ask.max_output_tokens', 700),
            self::MAX_OUTPUT_TOKENS, self::MIN_OUTPUT_TOKENS, self::HARD_OUTPUT_TOKENS);
    }

    /** سقفُ خطواتِ النموذجِ الفعليّ */
    public static function maxModelSteps(): int
    {
        return self::clamp(setting('ask.max_model_steps', 6),
            self::MAX_TOOL_CALLS, self::MIN_MODEL_STEPS, self::HARD_MODEL_STEPS);
    }

    /** سقفُ تنفيذاتِ الأدواتِ الفعليّ — **مستقلٌّ عن الخطوات** */
    public static function maxToolCalls(): int
    {
        return self::clamp(setting('ask.max_tool_calls', 6),
            self::MAX_TOOL_CALLS, self::MIN_TOOL_CALLS, self::HARD_TOOL_CALLS);
    }

    /** سقفُ الكلفةِ المقدَّرةِ للطلب — `0.0` يعني ألّا سقفَ تقديريّ */
    public static function costCeiling(): float
    {
        return max(0.0, (float) setting('ask.cost_ceiling', 0));
    }

    /**
     * **قيمةٌ داخلَ مدىً** — والخارجُ عن المدى يُقصّ إليه لا يُقبَل.
     *
     * ── **ولمَ يُكتَب المفتاحُ والافتراضيُّ حرفيّاً في كلِّ نداء؟** ──
     *
     * كانا يُمرَّران وسيطين إلى هذه الدالّة، **فسقط حارسان** في أوّلِ بوّابةٍ
     * كاملة: `SettingsCenterTest` يمسح `app/` على النمطِ
     * `setting('<مفتاح>'` ليُثبِت أنّ كلَّ مدخلٍ في الشاشةِ **له قارئٌ حقيقيّ**،
     * و`SettingsModelTest` يقارن الافتراضيَّ المُعلَنَ في الكتالوجِ **بالوسيطِ
     * الثاني الحرفيّ**. ومفتاحٌ يصل متغيّراً لا يراه المسحُ، فيبدو المدخلُ
     * ميّتاً وهو حيّ — **والشاشةُ تَعِد بأثرٍ لا دليلَ عليه**.
     *
     * والتكرارُ بين الحرفيِّ والثابتِ مقصودٌ إذاً، **ويحرسه اختبارٌ** يُقارن
     * الاثنين بالكتالوج فلا ينحرفان صامتين.
     */
    /**
     * @param  int  $min  **الأرضيّةُ الصلبة** — وكانت `1` فصار الإعدادُ يُعطّل
     *   المنتجَ بدل أن يضبطه (قبولُ الإنتاج · `OUTPUT_LIMIT`).
     */
    private static function clamp(mixed $v, int $default, int $min, int $hard): int
    {
        $n = is_numeric($v) ? (int) $v : $default;

        return max($min, min($hard, $n));
    }

    // ── حدودُ المدخل ────────────────────────────────────────────────────

    /**
     * **يُطهّر السؤالَ ويقصّه** — ويُعيد `null` إن لم يبقَ شيء.
     *
     * **والطمسُ على السؤالِ نفسِه مقصود:** مستخدمٌ يلصق مفتاحاً في سؤالِه
     * («لماذا يفشل هذا المفتاح sk-…؟») كان سيُرسله إلى مزوّدٍ خارجيٍّ ويكتبه
     * في أثرِ التدقيق. **والخطأُ خطؤه — والحمايةُ مسؤوليّتُنا.**
     */
    public static function sanitizeQuestion(string $raw): ?string
    {
        $q = trim(preg_replace('/\s+/u', ' ', $raw) ?? '');
        if ($q === '') return null;

        $q = Redactor::text($q);

        return mb_substr($q, 0, self::MAX_QUESTION_CHARS);
    }
}
