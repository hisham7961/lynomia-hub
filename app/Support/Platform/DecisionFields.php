<?php

namespace App\Support\Platform;

use Illuminate\Database\Eloquent\Model;

/**
 * **حقولُ القرار — ما لا يُكتب من نموذجِ الإدخالِ العامّ.**
 *
 * أثبت الخبيرُ ١٤ في مجلس الخبراء أنّ موظّفاً بلا أيِّ رايةٍ فتح «＋ طلب إجازة»
 * من ملفّه، فوصل إلى نموذجِ وحدةِ `leaves` العامّ، **واختار «معتمد» من قائمةِ
 * الحالة**، فحُفظ: `status: معتمد · mgr_id: NULL`. **إجازةٌ معتمدةٌ بلا معتمِد.**
 * وزاد: أنشأ طلباً **باسمِ زميلتِه** بالحالةِ نفسِها. والأثرُ ليس عرضاً — الحالةُ
 * «معتمد» تُشغّل خصمَ الرصيد (`LeaveRequest::syncBalance`) وتجعل صاحبَها معذوراً
 * في نداءِ اليوم: يمنح نفسَه أيّاماً ويُعفي نفسَه من الحضورِ بنقرتين.
 *
 * **والسببُ الجذريّ ليس غيابَ حارس.** للمنتجِ مسارُ قرارٍ صحيحٌ قائمٌ
 * (`LeaveDecisionController`) يفرض التسلسلَ ويمنع البتَّ في طلبِ النفسِ بـ403
 * ويُلزم بسببٍ عند الرفض — لكنّ **النموذجَ العامَّ يلتفّ حولَه**: يرسم كلَّ أعمدةِ
 * السجلّ حقولَ إدخالٍ سواءً، و`status` حقلُ **قرارٍ** لا حقلُ إدخال.
 *
 * **ولماذا هنا لا في المتحكّم؟** لأنّ للكتابةِ العامّةِ باباً ثانياً: الاستيراد
 * (`ImportController`) يكتب على النموذجِ مباشرةً بلا `fill()`، وخمسةُ أدوارٍ كاملةِ
 * النطاقِ تملك `leaves:a` بلا `hr` ولا رايةِ اعتماد — فحارسٌ في بابٍ واحدٍ يترك
 * البابَ الآخرَ مفتوحاً على العيبِ نفسِه.
 *
 * **ولا تُنزع قدرةٌ من أحد:** الحقلُ باقٍ، والشاشةُ باقية، والمسارُ باقٍ. من يملك
 * البتَّ يكتبه كما كان، ومن لا يملكه يُردُّ حقلُه إلى قيمتِه السابقةِ (أو إلى
 * القيمةِ الابتدائيّةِ الآمنةِ في الإنشاء) ويمضي طلبُه — فيطلب ولا يبتّ.
 */
final class DecisionFields
{
    /**
     * `الوحدة => [الحقل => القيمةُ الابتدائيّةُ الآمنة]`.
     *
     * والقيمةُ الابتدائيّةُ ليست زينة: حالةٌ فارغةٌ تُنتج عيبَ A-1 نفسَه — سجلٌّ
     * بلا حالةٍ تقرؤه القوائمُ قراءاتٍ متضاربة (`NULL NOT IN (…)` لا يصدُق في SQL).
     */
    public const MAP = [
        'leaves' => ['status' => 'مقدّم'],
    ];

    /**
     * **القيمُ التي لا يكتبها إلّا من يملك البتّ.**
     *
     * والقائمةُ قيمٌ لا «أيُّ تغيير» — وهذا فرقٌ يحفظ قدرةً: صاحبُ الطلبِ يسحب
     * بطاقتَه إلى «ملغى» أو يعدّل تواريخَه ما دام معلّقاً، وذاك حقُّه لا اعتداء.
     * الممنوعُ أن يكتب **قرارَ غيرِه في طلبِه**.
     */
    public const DECIDED = [
        'leaves' => ['status' => ['معتمد', 'مرفوض', 'موافقة المدير', 'موافقة الموارد البشرية']],
    ];

    /** أهذه قيمةُ قرارٍ في هذا الحقل؟ */
    public static function isDecidedValue(string $module, string $key, $value): bool
    {
        return in_array((string) $value, self::DECIDED[$module][$key] ?? [], true);
    }

    /**
     * التقاطُ حقولِ القرارِ **قبل** التعبئة: `المفتاح => [العمود, الآمنة, ما كان]`.
     * تُستدعى قبل أيِّ كتابة، ويُمرَّر ناتجُها إلى `enforce()` بعدها.
     */
    public static function capture(string $module, array $def, Model $m): array
    {
        $out = [];
        foreach (self::MAP[$module] ?? [] as $key => $safe) {
            foreach ($def['fields'] ?? [] as $f) {
                if (($f['key'] ?? null) !== $key) continue;
                $col = $f['col'];
                $out[$key] = [$col, $safe, $m->{$col} ?? null];
                break;
            }
        }

        return $out;
    }

    /**
     * ردُّ كلِّ حقلِ قرارٍ كُتبت فيه **قيمةُ قرارٍ** بيدِ من لا يملك البتّ.
     *
     * والمقارنةُ بما كان لا بالقيمةِ الواردة: كتابةٌ لم تمسَّ الحقلَ لا تُحاسَب،
     * فلا يُقلَب طلبٌ قائمٌ رأساً على عقبٍ لأنّ صاحبَه عدّل سطرَ الملاحظات.
     */
    public static function enforce(string $module, Model $m, array $captured): void
    {
        if (! $captured) return;

        $u = auth()->user();
        if (! $u) return;   // بلا فاعلٍ بشريّ: بذرٌ أو أمرُ طرفيّةٍ أو مُجدوِل — لا أحدَ يُحرَس منه

        foreach ($captured as $key => [$col, $safe, $was]) {
            $now = $m->{$col} ?? null;
            if ((string) $now === (string) ($was ?? '')) continue;          // لم يتغيّر
            if (! self::isDecidedValue($module, $key, $now)) continue;      // ليست قيمةَ قرار
            if (self::mayDecide($module, $u, $m)) continue;

            // في التحديثِ تُردُّ القيمةُ السابقة، وفي الإنشاءِ القيمةُ الابتدائيّةُ الآمنة
            $m->{$col} = $m->exists ? $was : $safe;
        }
    }

    /**
     * **حارسُ أبوابِ الحالةِ المباشرة** — سحبُ بطاقةٍ في كانبان (`setStatus`)،
     * ونظيرُها في الجوّال، والإجراءُ الجماعيّ. هذه الأبوابُ لا تمرّ بـ`fill()`
     * وتكتب العمودَ رأساً، **وقد أثبت الاختبارُ أنّها كانت مفتوحةً فعلاً**:
     * موظّفٌ سحب بطاقةَ إجازتِه إلى «معتمد» فاعتُمدت وخُصم رصيدُه.
     *
     * وهنا **رفضٌ صريحٌ لا ردٌّ صامت**: البابُ لا يفعل غيرَ تغييرِ الحالة، فردُّها
     * بصمتٍ رسالةُ نجاحٍ كاذبة. والرسالةُ تدلّ على البابِ الصحيح.
     */
    public static function guardStatusWrite(string $module, Model $m, string $to): void
    {
        if (empty(self::DECIDED[$module])) return;                // وحدةٌ بلا قيمِ قرارٍ أصلاً
        $field = hub_status_field($module);
        $key = (string) (is_array($field) ? ($field['key'] ?? 'status') : 'status');
        if (! self::isDecidedValue($module, $key, $to)) return;

        $u = auth()->user();
        if (! $u || self::mayDecide($module, $u, $m)) return;

        abort(403, 'الحالةُ «' . $to . '» قرارٌ لا إدخال — يقرّرها مديرُ الموظّف '
            . 'أو الموارد البشريّة من أزرارِ القرار على الطلب');
    }

    /**
     * **سلطةُ البتِّ تُقرأ من مالكِها لا تُعاد كتابتُها هنا.**
     *
     * `LeaveDecisionController::mayDecideOn` هي التعريفُ الوحيدُ لـ«من يبتّ في
     * طلبِ إجازة»، ويقرؤها مسارُ القرارِ وواجهةُ الأزرارِ وهذا الحارسُ معاً.
     */
    public static function mayDecide(string $module, $u, Model $m): bool
    {
        return match ($module) {
            'leaves' => $m instanceof \App\Models\LeaveRequest
                && \App\Http\Controllers\Web\LeaveDecisionController::mayDecideOn($u, $m),
            default => false,
        };
    }
}
