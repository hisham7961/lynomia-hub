<?php

namespace App\Support;

/**
 * **«الشهر» مفهومٌ زمنيٌّ عومل معاملةَ نصٍّ حرّ** (مجلس الخبراء · DB-01).
 *
 * `payroll_runs.month` عمودٌ نصّيٌّ حرّ ونوعُ حقلِه `text` في سجلِّ الوحدات، فحُفظ
 * «رواتب أغسطس» مرّتين لشركةٍ واحدة: مرّةً `2026-08` ومرّةً «أغسطس 2026». ولا
 * القاعدةُ تعرف أنّهما شهرٌ واحد ولا التطبيقُ يسأل. **والأثرُ ليس تكرارَ صفّ:**
 * الاعتمادُ يولّد قيدَ يوميّةٍ لكلِّ مسيّر — فمسيّران معتمدان صرفُ راتبٍ مرّتين.
 *
 * فهذا **مطبِّعٌ واحد**: نصُّ الشهرِ كما كتبه المستخدم ⇒ أوّلُ يومٍ من الشهر.
 * ويبقى `month` النصّيُّ كما هو للعرضِ والتوافقِ الخلفيّ — **لا يُحوَّل ولا يُكسر
 * عقد**؛ يُضاف بجانبِه `month_key` للمقارنةِ وحدَها.
 *
 * **وما لا يُفهَم يُترك `null`** — فلا يُمنع الحفظُ بحجّةِ صيغةٍ لم يعرفها
 * المطبِّع. الحارسُ يمنع المتطابقَ المعروف، لا المجهول.
 */
final class PayrollMonth
{
    /** أسماءُ الشهورِ العربيّةُ الشائعةُ والشاميّةُ واللاتينيّة ⇒ رقمُ الشهر */
    private const NAMES = [
        // الشائعة (مصر/الخليج)
        'يناير' => 1, 'فبراير' => 2, 'مارس' => 3, 'ابريل' => 4, 'أبريل' => 4,
        'مايو' => 5, 'يونيو' => 6, 'يونيه' => 6, 'يوليو' => 7, 'يوليه' => 7,
        'اغسطس' => 8, 'أغسطس' => 8, 'سبتمبر' => 9, 'اكتوبر' => 10, 'أكتوبر' => 10,
        'نوفمبر' => 11, 'ديسمبر' => 12,
        // الشاميّة
        'كانون الثاني' => 1, 'شباط' => 2, 'اذار' => 3, 'آذار' => 3, 'نيسان' => 4,
        'ايار' => 5, 'أيار' => 5, 'حزيران' => 6, 'تموز' => 7, 'اب' => 8, 'آب' => 8,
        'ايلول' => 9, 'أيلول' => 9, 'تشرين الاول' => 10, 'تشرين الأول' => 10,
        'تشرين الثاني' => 11, 'كانون الاول' => 12, 'كانون الأول' => 12,
        // اللاتينيّة (كاملةً ومختصرة)
        'january' => 1, 'jan' => 1, 'february' => 2, 'feb' => 2, 'march' => 3, 'mar' => 3,
        'april' => 4, 'apr' => 4, 'may' => 5, 'june' => 6, 'jun' => 6, 'july' => 7, 'jul' => 7,
        'august' => 8, 'aug' => 8, 'september' => 9, 'sep' => 9, 'sept' => 9,
        'october' => 10, 'oct' => 10, 'november' => 11, 'nov' => 11, 'december' => 12, 'dec' => 12,
    ];

    /** أرقامٌ عربيّةٌ-هنديّةٌ وفارسيّة ⇒ لاتينيّة */
    private const DIGITS = ['٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9'];

    /** نصُّ الشهرِ ⇒ `Y-m-01`، أو `null` إن لم يُفهَم */
    public static function key(?string $raw): ?string
    {
        $s = trim((string) $raw);
        if ($s === '') return null;

        $s = strtr($s, self::DIGITS);
        $s = str_replace(['ـ', '،'], ['', ' '], $s);          // تطويلٌ وفاصلةٌ عربيّة
        $s = preg_replace('/\s+/u', ' ', $s);
        $low = mb_strtolower($s, 'UTF-8');

        // ١) رقميّةٌ صريحة: 2026-08 · 2026/8 · 2026-08-01
        if (preg_match('/(?<y>\d{4})\s*[-\/.]\s*(?<m>\d{1,2})(?:\s*[-\/.]\s*\d{1,2})?$/u', $s, $m)) {
            return self::build((int) $m['y'], (int) $m['m']);
        }
        // ٢) الشهرُ أوّلاً: 08/2026 · 8-2026
        if (preg_match('/^(?<m>\d{1,2})\s*[-\/.]\s*(?<y>\d{4})$/u', $s, $m)) {
            return self::build((int) $m['y'], (int) $m['m']);
        }
        // ٣) اسمُ شهرٍ + سنة (بأيِّ ترتيب، وبأيِّ نصٍّ حولَه: «رواتب أغسطس 2026»)
        if (preg_match('/(?<y>\d{4})/u', $s, $y)) {
            foreach (self::NAMES as $name => $num) {
                if (mb_strpos($low, mb_strtolower($name, 'UTF-8'), 0, 'UTF-8') !== false) {
                    return self::build((int) $y['y'], $num);
                }
            }
        }

        return null;
    }

    private static function build(int $year, int $month): ?string
    {
        if ($month < 1 || $month > 12 || $year < 1900 || $year > 2999) return null;

        return sprintf('%04d-%02d-01', $year, $month);
    }
}
