<?php

namespace App\Support\Ai\Routing;

use App\Models\AiModel;
use App\Models\AiUsageEvent;
use App\Support\Tri;

/**
 * **ما تحتاجه ميزةُ Hub من النموذجِ فعلاً** — لا ما يكفي لتوليدِ نصّ.
 * (المرحلة ٥ · W2)
 *
 * ── **الدرسُ الإنتاجيُّ الذي وُلد منه هذا الصنف** ──
 *
 * نموذجٌ `chat = true` و`tools = true` **قد يبقى غيرَ صالحٍ** لـ«اسأل Hub»
 * ضمنَ ميزانيّةٍ بعينِها: يُنفق سقفَه تفكيراً قبل أن يُصدر طلبَ أداة. فبين
 * «يقدر على التوليد» و«يصلح لهذا الغرض» فرقٌ **ليس في المخطَّطِ قبل اليوم**.
 *
 * ── **ستُّ بوّاباتٍ مستقلّةٍ لا واحدة** ──
 *
 * | البوّابة | السؤال | الطبقة |
 * |---|---|---|
 * | **القدرة** | أيستطيع؟ | `AiModelFacts` · `capabilities` |
 * | **التوافر** | أهو مُفعَّلٌ وموجود؟ | `AiModel::enabled` · `AiProfiles::UNROUTABLE` |
 * | **الصحّة** | أهو حيٌّ الآن؟ | `AiRouting` · تهدئةُ المزوّد |
 * | **السياسة** | أمسموحٌ لهذه الميزةِ وهذا المستخدم؟ | `AiPolicy` |
 * | **الميزانيّة** | أيتّسع له الرصيد؟ | `AiBudgets` |
 * | **الملاءمة** | **أيصلح لهذا الغرضِ بعينِه؟** | ← **هذا الصنف** |
 *
 * وخلطُها يُنتج تشخيصاً كاذباً: «النموذجُ لا يعمل» عن نموذجٍ يعمل ولا يُلائم،
 * أو «الإعدادُ ناقص» عن ميزانيّةٍ نفدت.
 *
 * ── **والمجهولُ يُغلِق — بشرطِ ألّا يُهدَر دليلٌ نملكه** ──
 *
 * قدرةٌ مطلوبةٌ حالتُها `unknown` **تمنع** التوجيه، كما `Tri::allowsExecution`
 * في كلِّ الطبقاتِ القائمة. **لكنّ صمتَ البوّابةِ ليس كلَّ ما نملك**: إن كان
 * دفترُنا يحمل دورةً ناجحةً نفّذ فيها هذا النموذجُ أداةً بالفعل، فتلك
 * **ملاحظةٌ مقيسةٌ أقوى من إعلانٍ غائب** — ويمرّ بها.
 *
 * فالقاعدة: `أُعلِنت true` **أو** `لوحظت عملاً` ⟵ يمرّ. وما عداه يُمنَع
 * بسببٍ يُقال.
 *
 * ── **ولا اسمَ مزوّدٍ ولا نموذجٍ هنا** ──
 *
 * الحاجاتُ مكتوبةٌ بمفرداتِ `AiModelFacts::CAPABILITIES`، والأغراضُ بمفاتيحِ
 * ميزاتِ Hub. فنموذجٌ جديدٌ يمرّ بلا سطرٍ يُضاف.
 */
final class AiPurposes
{
    /** مفتاحُ ميزةِ «اسأل Hub» — هو نفسُه `feature` في سياقِ الحوكمة */
    public const ASK = 'ask';

    /** مفتاحُ ميزةِ المدقّق (كواشفُ الذكاء) — `feature` في سياقِ الحوكمةِ وسجلِّ الاستهلاك */
    public const AUDIT = 'audit';

    /**
     * **ما تحتاجه كلُّ ميزةٍ من قدرات** — صلبٌ لا يُضبَط من شاشة.
     *
     * و«اسأل Hub» يحتاج اثنتين لا واحدة:
     *
     *  · **`chat`** — توليدُ نصٍّ في محادثة. بديهيّةٌ تُكتَب لأنّ ما لا يُكتَب
     *    لا يُفحَص.
     *  · **`tools`** — **إصدارُ طلبِ أداة**. وهذه هي الفجوةُ التي كانت: غرضُ
     *    `general` يشترط `chat` وحدَها، فنموذجٌ لا يُصدر طلباتِ أدواتٍ يجلس
     *    شرعيّاً على رأسِ سلسلةِ المساعد — **ومسارُ المساعدِ كلُّه دورةُ
     *    أدوات**.
     *
     * @var array<string, list<string>>
     */
    public const NEEDS = [
        self::ASK => ['chat', 'tools'],
        // **والمدقّقُ يحتاج التوليدَ وحده** — يقرأ مقتطفاتٍ ويُعيد حكماً مُهيكلاً، بلا أدوات:
        // الخادمُ هو من قرأ وانتقى، والنموذجُ لا يطلب شيئاً ولا يرى إلّا ما أُعطي
        self::AUDIT => ['chat'],
    ];

    /** حالاتُ الملاءمة — ثلاثٌ لا اثنتان */
    public const FIT      = 'FIT';        // قدراتٌ مُعلَنةٌ تكفي
    public const OBSERVED = 'OBSERVED';   // مجهولٌ في الإعلانِ ومُثبَتٌ بالعمل
    public const UNFIT    = 'UNFIT';      // ينقصه ما لا يُستغنى عنه

    /**
     * **قدراتُ هذه الميزة** — أو فراغٌ لميزةٍ لم تُعلن حاجةً.
     *
     * @return list<string>
     */
    public static function needs(string $feature): array
    {
        return self::NEEDS[trim($feature)] ?? [];
    }

    /**
     * **أيُلائم هذا النموذجُ هذه الميزة؟**
     *
     * @return array{ok: bool, state: string, missing: list<string>, why: ?string}
     */
    public static function suitability(AiModel $model, string $feature): array
    {
        $needs = self::needs($feature);
        if ($needs === []) {
            return ['ok' => true, 'state' => self::FIT, 'missing' => [], 'why' => null];
        }

        $caps     = is_array($model->capabilities) ? $model->capabilities : [];
        $missing  = [];
        $observed = false;

        foreach ($needs as $cap) {
            $fact = $caps[$cap] ?? null;
            $v    = Tri::of(is_array($fact) ? ($fact['v'] ?? null) : $fact);

            if ($v === true) continue;

            /*
             * **ودليلُ الدفترِ يسبق صمتَ البوّابة** — لا يسبق نفيَها.
             *
             * `false` إعلانٌ صريحٌ بأنّ النشرَ لا يدعمها، فلا تنقضه ملاحظة.
             * أمّا `unknown` فغيابُ إعلانٍ، ودورةٌ ناجحةٌ نفّذ فيها هذا
             * النموذجُ أداةً **تُثبِتها عملاً**. وهذا تطبيقُ القاعدةِ نفسِها
             * التي تجعل فاحصَ المستوى E يكتب `verified`: **الإثباتُ يعلو
             * الإعلان**.
             */
            if ($v === null && self::proven($model, $cap)) {
                $observed = true;
                continue;
            }

            $missing[] = $cap;
        }

        if ($missing !== []) {
            return [
                'ok'      => false,
                'state'   => self::UNFIT,
                'missing' => $missing,
                'why'     => 'ينقص النموذجَ لهذا الغرض: ' . implode(' · ', $missing)
                             . ' — و«غيرُ معروفة» لا تُرقّى إلى «مدعومة» بالصمت',
            ];
        }

        return ['ok' => true, 'state' => $observed ? self::OBSERVED : self::FIT,
                'missing' => [], 'why' => null];
    }

    /**
     * **أثبت هذا النموذجُ هذه القدرةَ عملاً في دفترِنا؟**
     *
     * ولا تُثبَت إلّا `tools` اليوم، لأنّها القدرةُ الوحيدةُ التي يترك
     * استعمالُها **أثراً لا يُشتبَه فيه**: عمودُ `tool_requested` لا يُملأ
     * إلّا باسمٍ من مفرداتِ `AskTools::TOOLS` المغلقة، ولا يُكتَب إلّا من
     * ردٍّ حملَ طلبَ أداةٍ فعلاً (المهاجرة `2026_10_06_000001`).
     *
     * **وما لا يترك أثراً لا يُدّعى**: قدرةٌ أخرى تبقى على إعلانِها.
     */
    private static function proven(AiModel $model, string $capability): bool
    {
        if ($capability !== 'tools') return false;
        if (! $model->exists) return false;

        /*
         * **ولا ذاكرةَ ساكنةٌ هنا** — وقد كُتبت ثمّ أُزيلت باختبارٍ أسقطها.
         *
         * ذاكرةٌ `static` مفاتيحُها معرّفاتُ النماذجِ **تعمّر ما عمّرت
         * العمليّة**: في عاملِ طابورٍ أو خادمٍ مقيمٍ ذلك عمرٌ بالساعات. فنموذجٌ
         * حُسم «بلا دليل» عند أوّلِ طلبٍ يبقى كذلك بعد أن يُثبِت نفسَه بعشرِ
         * دوراتٍ ناجحة — **وهو بالضبط العطلُ الذي وُجد هذا الصنفُ ليمنعَه**،
         * مقلوباً.
         *
         * والثمنُ المُوفَّرُ لم يكن يستحقّ: `EXISTS` على فهرسٍ لسلسلةٍ أقصاها
         * ثلاثةُ نماذجَ — ستُّ جُملٍ مجهريّةٍ في الطلبِ الواحد، بجانبِ رحلةِ
         * شبكةٍ إلى مزوّدٍ تُقاس بمئاتِ أجزاءِ الثانية.
         */
        return AiUsageEvent::query()
            ->where('model_id', $model->id)
            ->whereNotNull('tool_requested')
            ->exists();
    }

    /** **وسمٌ قصيرٌ للشاشة** — والتفصيلُ في `why` */
    public const TAG = [
        self::FIT      => 'مُلائم',
        self::OBSERVED => 'مُثبَتٌ عملاً',
        self::UNFIT    => 'غيرُ مُلائم',
    ];
}
