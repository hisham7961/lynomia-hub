<?php

namespace Tests\Feature;

use App\Models\AlertRule;
use App\Models\AuditEntry;
use App\Models\FinDocument;
use App\Models\Idea;
use App\Models\Project;
use App\Models\RecurringDoc;
use RuntimeException;
use Tests\TestCase;

/**
 * **كتابتان في عمليّةٍ واحدة: إمّا معاً أو لا شيء** — البندان #3 (DI-07)
 * و#6 (F-12) في `docs/TECH_DEBT.md`.
 *
 * ── **ما يقيسه هذا الملفّ** ──
 *
 * قياسُ الجولةِ الثانيةِ وجد #3 **نصفَ مغلق**: الرواتبُ والمستنداتُ الماليّةُ
 * داخلَ معاملات، و`LegalController` و`InnovationController` بلا معاملةٍ
 * واحدة. ووجد #6 مفتوحاً بالكامل: `DB::transaction` **صفرٌ** في
 * `HubAutomation`. وهذه ليست أشكالاً: في كلِّ موضعٍ منها **كتابتان
 * مترابطتان** تُترك أُولاهما قائمةً إذا سقطت الثانية.
 *
 * ── **ولماذا يُصطنَع الفشل؟** ──
 *
 * لأنّ العيبَ **لا يظهر في المسارِ السعيد**: الطلبُ ينجح، والشاشةُ تقول
 * «رُقّيت»، ولا أحدَ يرى شيئاً. ولا يظهر إلّا حين تسقط الكتابةُ الثانية —
 * قيدٌ، أو انقطاعُ اتّصال، أو مهلةٌ انتهت — **وحينها يكون الضررُ في قاعدةِ
 * الإنتاجِ لا في شاشة**. فالاختبارُ يُسقط الكتابةَ الثانيةَ عمداً ويسأل عن
 * الأولى.
 *
 * وهذا هو **الإثباتُ لا الادّعاء** الذي يطلبه `CLAUDE.md`: الاختبارُ كُتب
 * أوّلاً فسقط — مشروعٌ يتيمٌ واحد، وقاعدةٌ مفعَّلةٌ بلا أثرِ تدقيق — ثمّ
 * أُصلح الموضعان.
 */
class WriteAtomicityTest extends TestCase
{
    /**
     * **ترقيةُ الفكرةِ إلى مشروع: مشروعٌ بلا ربطٍ لا يبقى.**
     *
     * المسارُ كتابتان: `Project::create` ثمّ `$idea->update(project_id…)`.
     * وبلا معاملةٍ كان سقوطُ الثانيةِ يترك **مشروعاً يتيماً** في الوحدة: لا
     * فكرةَ تشير إليه، ويظهر في كانبان المشاريعِ كعملٍ حقيقيّ، **والفكرةُ
     * تبقى قابلةً للترقيةِ مرّةً أخرى** فيُولَد له توأم.
     */
    public function test_ترقيةُ_الفكرةِ_لا_تترك_مشروعاً_يتيماً_إن_سقط_الربط(): void
    {
        $this->seedCore();

        $idea = Idea::create([
            'title' => 'منصّةُ حجزٍ ذاتيّة', 'problem' => 'الحجزُ بالهاتف',
            'idea' => 'بوّابةٌ للعميل', 'impact' => 8, 'confidence' => 7, 'ease' => 6,
            'status' => 'معتمدة',
        ]);

        // الكتابةُ الثانيةُ تسقط — كما يسقط قيدٌ أو ينقطع اتّصالٌ في الإنتاج
        Idea::updating(function (): void {
            throw new RuntimeException('سقوطُ الربطِ مُصطنَع');
        });

        try {
            $this->actingAs($this->owner)
                ->withoutExceptionHandling()
                ->post('/ideas/' . $idea->id . '/promote');
            $this->fail('كان على الكتابةِ الثانيةِ أن تسقط — الاختبارُ نفسُه معطوب');
        } catch (RuntimeException $e) {
            $this->assertSame('سقوطُ الربطِ مُصطنَع', $e->getMessage());
        }

        $this->assertSame(0, Project::where('name', 'منصّةُ حجزٍ ذاتيّة')->count(),
            'مشروعٌ يتيمٌ بقي بعد سقوطِ الربط — الكتابتان ليستا في معاملة');

        $this->assertNull($idea->fresh()->project_id,
            'الفكرةُ ربطت بمشروعٍ لا وجودَ له');
    }

    /**
     * **تفعيلُ قاعدةِ التنبيه: تغييرٌ بلا أثرِ تدقيقٍ لا يُثبَّت.**
     *
     * وقاعدةُ التنبيهِ ضابطٌ تشغيليّ: من فعّلها ومتى **سؤالُ تدقيقٍ لا
     * فضول**. فتغييرُ الحالةِ وقيدُ التدقيقِ واقعةٌ واحدةٌ تُكتَب مرّتين،
     * وبقاءُ إحداهما دون الأخرى يُنتج سجلّاً يقول غيرَ ما تقوله القاعدة.
     *
     * **والقيمةُ هنا أقلُّ من سابقتِها ويُقال ذلك صراحةً**: لا مشروعَ يتيمَ
     * ولا صفَّ مكرّر — إنّما فجوةٌ في الأثر. لكنّ المستودعَ يضع `hub_audit`
     * داخلَ المعاملةِ في **سبعةَ عشرَ موضعاً**، فالشذوذُ كان هنا لا هناك.
     */
    public function test_تفعيلُ_قاعدةِ_التنبيهِ_لا_يثبت_بلا_أثرِ_تدقيق(): void
    {
        $this->seedCore();
        $this->artisan('hub:alerts-starter')->assertSuccessful();

        /*
         * **والترتيبُ صريحٌ بالمعرّف** — `firstOrFail()` بلا ترتيبٍ على عدّةِ
         * صفوفٍ **قرعةٌ** يحذّر منها `CLAUDE.md`: MariaDB تُعيد صفّاً وMySQL 8
         * آخر، فيخضرُّ الاختبارُ هنا ويسقط على CI بلا سببٍ في الشيفرة.
         */
        $rule = AlertRule::where('mod', 'contracts')
            ->where('status', '!=', 'مفعّلة')
            ->orderBy('id')
            ->firstOrFail();

        $before = (string) $rule->status;

        // قيدُ التدقيقِ يسقط — والتغييرُ الذي يسبقه يجب ألّا يثبت وحدَه
        AuditEntry::creating(function (): void {
            throw new RuntimeException('سقوطُ قيدِ التدقيقِ مُصطنَع');
        });

        try {
            $this->actingAs($this->owner)
                ->withoutExceptionHandling()
                ->post("/legal/rules/{$rule->id}/enable");
            $this->fail('كان على قيدِ التدقيقِ أن يسقط — الاختبارُ نفسُه معطوب');
        } catch (RuntimeException $e) {
            $this->assertSame('سقوطُ قيدِ التدقيقِ مُصطنَع', $e->getMessage());
        }

        $this->assertSame($before, (string) $rule->fresh()->status,
            'القاعدةُ فُعّلت ولا أثرَ تدقيقٍ لتفعيلها — الكتابتان ليستا في معاملة');
    }

    /**
     * **دورةُ المتكرّر: مستندٌ بلا تقديمِ المؤشّرِ لا يبقى** (البند #6 · F-12).
     *
     * ── **لماذا هذا الموضعُ بعينِه أخطرُ من سابقَيه** ──
     *
     * `hub:automation` تعمل **كلَّ صباحٍ بلا من يراها**. فعطلٌ هنا لا يُبلَّغ
     * لمستخدمٍ ينتظر رداً — يُكتَب في السجلّ ويمضي، ويظهر أثرُه بعد أسابيعَ
     * **فاتورةً مكرّرةً في دفترٍ ماليّ**.
     *
     * ── **والفجوةُ ما تبقّى بعد إصلاحٍ سابقٍ صحيح** ──
     *
     * المؤشّرُ `next` يُحفَظ **مع كلِّ دورةٍ** لا بعد الحلقة كلِّها، وذلك
     * إصلاحٌ قديمٌ موثَّقٌ في الشيفرة يحرسه `AutomationIdempotencyTest`.
     * لكنّه **يرتّب الكتابتَين ولا يجعلهما واحدة**: بينهما نافذةٌ يسقط فيها
     * الحفظُ بعد أن التزم المستندُ — فيبقى مستندٌ ومؤشّرٌ لم يتقدّم،
     * **فيُولَّد له توأمٌ في صباحِ الغد**.
     *
     * وهذا الاختبارُ يُسقِط الكتابةَ الثانيةَ عمداً ويسأل عن الأولى.
     */
    public function test_دورةُ_المتكرّرِ_لا_تترك_مستنداً_بلا_تقديمِ_المؤشّر(): void
    {
        $this->seedCore();

        $rec = RecurringDoc::create([
            'name' => 'اشتراكُ استضافةٍ شهريّ', 'kind' => 'مصروف', 'amount' => 500,
            'currency' => 'د.ك', 'cycle' => 'شهري', 'auto_post' => true,
            'status' => 'مفعّل', 'next' => now()->subDay()->toDateString(),
        ]);
        $before = (string) $rec->next;

        // الكتابةُ الثانيةُ تسقط بعد أن التزم المستند — كما يسقط قيدٌ أو ينقطع اتّصال
        FinDocument::created(function (): void {
            throw new RuntimeException('سقوطُ تقديمِ المؤشّرِ مُصطنَع');
        });

        /*
         * **والأمرُ لا يُرمى منه استثناء**: `recurring()` يلفّ كلَّ متكرّرٍ
         * بـ`catch` كي لا يُوقف واحدٌ البقيّة. فالعطلُ يُبلَّغ ويمضي —
         * **وهو بالضبط ما يجعل هذا الصنفَ صامتاً**، والاختبارُ يسأل عن
         * الأثرِ في القاعدةِ لا عن رمزِ الخروج.
         */
        $this->artisan('hub:automation')->assertExitCode(0);

        $this->assertSame(0, FinDocument::where('description', 'LIKE', '%اشتراكُ استضافةٍ شهريّ%')->count(),
            'مستندٌ التزم ثمّ سقط تقديمُ المؤشّر — فيُولَّد له توأمٌ غداً. الكتابتان ليستا في معاملة');

        $this->assertSame($before, (string) $rec->fresh()->next,
            'المؤشّرُ تقدّم رغم سقوطِ الدورة — فالاستحقاقُ يُفوَّت بلا مستند');
    }
}
